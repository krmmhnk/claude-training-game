function addExp(amount) {
  state.exp += amount;
  while (state.level < MAX_LEVEL && state.exp >= LEVEL_THRESHOLDS[state.level + 1]) {
    state.level++;
  }
}
function getExpProgress() {
  const cur  = LEVEL_THRESHOLDS[state.level]     || 0;
  const next = LEVEL_THRESHOLDS[state.level + 1] || state.exp + 1;
  const prog = state.exp - cur;
  const need = next - cur;
  return { progress: prog, needed: need, pct: Math.min(100, Math.floor(prog / need * 100)) };
}

