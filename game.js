// ===== バトルシーン =====
function initScene() {
  heroScenePos   = 5;
  enemyActive    = false;
  enemyScenePos  = 90;
  enemySpawnTime = Math.random() < 0.75
    ? Math.floor(Math.random() * 12) + 8  // 8〜20秒のどこかで出現
    : -1;

  const heroEl  = document.getElementById('scene-hero');
  const enemyEl = document.getElementById('scene-enemy');
  const starEl  = document.getElementById('scene-star');

  if (heroEl) {
    heroEl.innerHTML  = buildCharSVG();
    heroEl.style.left = heroScenePos + '%';
    heroEl.className  = 'scene-hero';
  }
  if (enemyEl) { enemyEl.style.display = 'none'; enemyEl.className = 'scene-enemy'; }
  if (starEl)  { starEl.style.display  = 'none'; }
}

function updateScene() {
  heroScenePos = 5 + (1 - timeLeft / QUIZ_TIME) * 52;
  const heroEl = document.getElementById('scene-hero');
  if (heroEl && !heroEl.classList.contains('attacking') && !heroEl.classList.contains('damaged')) {
    heroEl.style.left = heroScenePos + '%';
  }

  if (!enemyActive && timeLeft === enemySpawnTime) {
    spawnEnemy();
  }

  if (enemyActive) {
    enemyScenePos -= 3.2;
    const enemyEl = document.getElementById('scene-enemy');
    if (enemyEl) enemyEl.style.left = enemyScenePos + '%';
  }
}

function spawnEnemy() {
  enemyActive   = true;
  enemyScenePos = 90;
  const enemyEl = document.getElementById('scene-enemy');
  if (enemyEl) {
    enemyEl.innerHTML     = buildEnemySVG();
    enemyEl.style.left    = enemyScenePos + '%';
    enemyEl.style.display = 'block';
    enemyEl.className     = 'scene-enemy';
  }
}

function sceneReact(isCorrect) {
  const heroEl  = document.getElementById('scene-hero');
  const enemyEl = document.getElementById('scene-enemy');
  const starEl  = document.getElementById('scene-star');

  if (isCorrect) {
    if (heroEl) heroEl.className = 'scene-hero attacking';
    if (enemyActive && enemyEl) {
      setTimeout(() => {
        enemyEl.className = 'scene-enemy defeated';
        if (starEl) {
          starEl.style.left    = (enemyScenePos + 1) + '%';
          starEl.style.bottom  = '28px';
          starEl.style.display = 'block';
          starEl.style.animation = 'none';
          void starEl.offsetWidth;
          starEl.style.animation = 'star-burst 0.6s ease-out forwards';
          setTimeout(() => { starEl.style.display = 'none'; }, 650);
        }
        setTimeout(() => { enemyEl.style.display = 'none'; }, 580);
      }, 200);
    }
    enemyActive = false;
    setTimeout(() => { if (heroEl) heroEl.className = 'scene-hero'; }, 450);
  } else {
    if (heroEl) {
      heroEl.className = 'scene-hero damaged';
      setTimeout(() => { heroEl.className = 'scene-hero'; }, 550);
    }
  }
}

// ===== タイマー =====
function startTimer() {
  clearTimer();
  timeLeft = QUIZ_TIME;
  initScene();
  updateTimerUI();

  timerInterval = setInterval(() => {
    timeLeft--;
    updateTimerUI();
    updateScene();
    if (timeLeft <= 0) {
      clearTimer();
      timeoutAnswer();
    }
  }, 1000);
}

function clearTimer() {
  if (timerInterval) { clearInterval(timerInterval); timerInterval = null; }
}

function updateTimerUI() {
  const fillEl = document.getElementById('timer-fill');
  const numEl  = document.getElementById('timer-num');
  if (!fillEl || !numEl) return;
  const pct    = Math.max(0, timeLeft / QUIZ_TIME * 100);
  fillEl.style.width = pct + '%';
  numEl.textContent  = timeLeft;
  const urgent = timeLeft <= 10;
  fillEl.className = 'timer-fill' + (urgent ? ' urgent' : '');
  numEl.className  = 'timer-num'  + (urgent ? ' urgent' : '');
}

function timeoutAnswer() {
  if (answered) return;
  answered = true;
  sceneReact(false);

  const q       = currentQuestions[currentQuestionIndex];
  const buttons = document.querySelectorAll('.choice-btn');
  buttons.forEach((btn, i) => { btn.disabled = true; if (i === q.correct) btn.classList.add('correct'); });

  const feedback   = document.getElementById('quiz-feedback');
  feedback.textContent = '⏰ 時間切れ！正解は ' + ['A','B','C','D'][q.correct] + '。' + q.explanation;
  feedback.className   = 'quiz-feedback feedback-ng';

  const isLast = currentQuestionIndex >= currentQuestions.length - 1;
  document.getElementById('next-btn').style.display = 'inline-block';
  document.getElementById('next-btn').textContent   = isLast ? '結果を見る ▶' : 'つぎへ ▶';
}

// ===== 問題描画 =====
function renderQuestion() {
  const q  = currentQuestions[currentQuestionIndex];
  answered = false;

  document.getElementById('quiz-q').textContent        = 'Q' + (currentQuestionIndex + 1) + '. ' + q.q;
  document.getElementById('q-current').textContent     = currentQuestionIndex + 1;
  document.getElementById('q-total').textContent       = currentQuestions.length;
  document.getElementById('quiz-feedback').textContent = '';
  document.getElementById('quiz-feedback').className   = 'quiz-feedback';
  document.getElementById('next-btn').style.display    = 'none';

  const choicesEl = document.getElementById('quiz-choices');
  choicesEl.innerHTML = '';
  q.choices.forEach((c, i) => {
    const btn = document.createElement('button');
    btn.className   = 'choice-btn';
    btn.textContent = ['A','B','C','D'][i] + '. ' + c;
    btn.onclick     = () => selectAnswer(i);
    choicesEl.appendChild(btn);
  });

  startTimer();
}

// ===== 回答処理 =====
function selectAnswer(index) {
  if (answered) return;
  answered = true;
  clearTimer();

  const q        = currentQuestions[currentQuestionIndex];
  const isCorrect = index === q.correct;
  sceneReact(isCorrect);

  const buttons  = document.querySelectorAll('.choice-btn');
  const feedback = document.getElementById('quiz-feedback');
  buttons.forEach((btn, i) => {
    btn.disabled = true;
    if (i === q.correct) btn.classList.add('correct');
    else if (i === index) btn.classList.add('wrong');
  });

  if (isCorrect) {
    feedback.textContent = '✓ ' + q.explanation;
    feedback.className   = 'quiz-feedback feedback-ok';
  } else {
    feedback.textContent = '✗ 不正解。' + q.explanation;
    feedback.className   = 'quiz-feedback feedback-ng';
  }

  const isLast = currentQuestionIndex >= currentQuestions.length - 1;
  document.getElementById('next-btn').style.display = 'inline-block';
  document.getElementById('next-btn').textContent   = isLast ? '結果を見る ▶' : 'つぎへ ▶';
}

// ===== 次の問題 =====
function nextQuestion() {
  currentQuestionIndex++;
  if (currentQuestionIndex >= currentQuestions.length) completeMission();
  else renderQuestion();
}

// ===== ミッションクリア =====
function completeMission() {
  const alreadyDone = state.completedMissions.includes(currentMission.id);
  const lvBefore    = state.level;
  let reward = '';

  if (!alreadyDone) {
    state.completedMissions.push(currentMission.id);
  }

  addExp(currentMission.exp);

  if (state.level > lvBefore) {
    reward = `🎉 LEVEL UP！ Lv.${state.level} になった！`;
    if (state.level === 2) reward += '\n👗 ふくカスタマイズが解放されました！';
    if (state.level === 3) reward += '\n💎 アクセサリーが解放されました！';
    if (state.level === 4) reward += '\n🌈 背景カラーが解放されました！\n⛵ GitHub の島への航路が開いた！';
    if (state.level === 5) reward += '\n👑 称号が解放されました！';
    if (state.level === 6) reward += '\n👁 目の色・髪の色が解放されました！\n🏆 全ミッションクリア！真の AI マスターだ！';
  } else {
    reward = `＋${currentMission.exp} EXP 獲得！` + (alreadyDone ? '（復習ボーナス）' : '');
  }

  saveState();
  document.getElementById('clear-msg').textContent    = `「${currentMission.title}」をクリアした！`;
  document.getElementById('clear-reward').textContent = reward;
  updateAllSprites();
  showScreen('screen-clear');
}

